You halt, as if time itself has paused.

In the stillness of that fleeting moment,
something deep beneath the pond stirs,
sensing your presence.

A ripple disturbs the silent waters for but an instant...

An orca slowly rises from the depths.

...Its eyes appear swollen.

Silent, the orca gazes at you,
its head nodding slowly, as if to acknowledge you.

It speaks, 
saying it has waited for you for countless ages.
It swears to offer all its strength to aid you.

But...
As you meet its drowsy, dream-laden gaze,
you realize that asking too much may be a burden too great.
